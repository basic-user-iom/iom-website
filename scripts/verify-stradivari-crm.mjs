import { createServer } from 'vite';
import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const out=resolve(root,'.qa-out/stradivari-crm');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(resolve(out,'index.html'),`<!doctype html><html><head><meta charset="utf-8"></head><body><div id="root"></div><script type="module">
import React from 'react';import {createRoot} from 'react-dom/client';
import {DemosView} from '/src/crm/DemosView.tsx';import {CrmI18nProvider} from '/src/crm/i18n.tsx';
import '/src/index.css';import '/src/crm/crm.css';
createRoot(document.getElementById('root')).render(React.createElement(CrmI18nProvider,null,React.createElement(DemosView)));
</script></body></html>`);
const server=await createServer({root,server:{host:'127.0.0.1',port:5184,strictPort:true}});
await server.listen();
const browser=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const checks=[],errors=[],failures=[];
const pass=name=>{checks.push(name);console.log('PASS',name);};
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050}});
 page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)failures.push({url:r.url(),status:r.status()});});
 await page.goto('http://127.0.0.1:5184/.qa-out/stradivari-crm/index.html');
 const card=page.locator('.crm-demos-card').filter({hasText:'Stradivari Amantes S3'});
 await card.waitFor();assert.equal(await card.count(),1);
 assert.equal(await card.getByRole('link',{name:'Preview',exact:true}).getAttribute('href'),'https://iobjectm.com/demos/stradivari-amantes-s3/');
 assert.equal(await card.locator('iframe').count(),0);pass('CRM lists one Stradivari card and Preview points to its final URL');
 await card.getByRole('button',{name:'Expand Stradivari Amantes S3'}).click();
 const embed=card.locator('iframe');await embed.waitFor();
 assert.equal(await embed.getAttribute('src'),'/demos/stradivari-amantes-s3/?crmEmbed=1');
 const frame=await (await embed.elementHandle()).contentFrame();
 await frame.waitForSelector('#fallback[hidden]',{state:'attached',timeout:30000});
 assert.equal(await frame.locator('canvas').count(),1);assert.equal(await frame.locator('input[type=password]').count(),0);
 pass('Expanded CRM iframe loads the v05 demo directly without a password');
 await frame.locator('[data-language="en"]').click();
 await frame.locator('[data-stage="2"]').click();await frame.waitForFunction(()=>[...document.querySelectorAll('.hotspot')].filter(b=>!b.hidden).length===3);
 assert.equal(await frame.locator('.hotspot:visible').count(),3);
 await frame.locator('.hotspot').nth(1).click();assert.equal(await frame.locator('#part-title').innerText(),'Open basket');
 await frame.locator('#close-detail').click();await frame.locator('#motion').click();assert.equal(await frame.locator('#motion').getAttribute('aria-pressed'),'true');
 await frame.locator('#motion').click();await frame.locator('[data-stage="3"]').click();await frame.locator('[data-band="high"]').click();
 pass('Embedded NL/EN, marker 02, animation and frequency selection work');
 await page.screenshot({path:resolve(out,'crm-expanded.png'),fullPage:true});
 await card.getByRole('button',{name:'Collapse Stradivari Amantes S3'}).click();assert.equal(await card.locator('iframe').count(),0);pass('Collapse unloads the iframe');
 await page.goto('http://127.0.0.1:5184/demos/stradivari-amantes-s3/?qa=1&lang=en');
 await page.waitForFunction(()=>window.__demo?.snapshot().ready);
 const snapshot=await page.evaluate(()=>window.__demo.snapshot());assert.equal(snapshot.assetVersion,'v05');assert.equal(snapshot.environment.id,'monochrome_studio_02');
 assert.match(await page.locator('meta[name=robots]').getAttribute('content'),/noindex/);
 await page.setViewportSize({width:390,height:844});await page.locator('[data-stage="2"]').click();await page.waitForFunction(()=>window.__demo?.snapshot().stage===2&&!window.__demo.snapshot().transitioning&&[...document.querySelectorAll('.hotspot')].filter(b=>!b.hidden).length===3);
 assert.equal(await page.locator('.hotspot:visible').count(),3);assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:resolve(out,'demo-mobile.png'),fullPage:true});
 pass('Direct demo URL loads the exact HDR and all three mobile markers without overflow');
 assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);pass('No JavaScript errors or failed HTTP requests');
 fs.writeFileSync(resolve(out,'verification.json'),JSON.stringify({checks,errors,failures,snapshot,browser:browser.version()},null,2));
}finally{await browser.close();await server.close();}
